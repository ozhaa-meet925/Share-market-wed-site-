const escapePattern = (keyword) => keyword.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

const COMPILED = SECTOR_KEYWORDS.map(([sector, keywords]) => [
  sector,
  new RegExp(`\\b(?:${keywords.map(escapePattern).join('|')})\\b`, 'i'),
]);

export const SECTOR_NAMES = SECTOR_KEYWORDS.map(([sector]) => sector);

export function detectSector(symbol, name) {
  const haystack = `${symbol || ''} ${name || ''}`.toUpperCase();
  for (const [sector, pattern] of COMPILED) {
    if (pattern.test(haystack)) return sector;
  }
  return 'Diversified';
}
